// Generates server redirect files from src/data/redirects.json into dist/:
//  - .htaccess  (Apache / LiteSpeed hosting)
//  - _redirects (Netlify / Cloudflare Pages)
// Also writes robots.txt and sitemap.xml.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const r = JSON.parse(readFileSync('src/data/redirects.json', 'utf8'));
const site = (process.env.SITE_URL ?? 'https://www.cspconsulting.ma').replace(/\/$/, '');
const base = (process.env.BASE_PATH ?? '/').replace(/\/$/, '');
const isProd = !process.env.BASE_PATH || process.env.BASE_PATH === '/';
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\ `]/g, '\\$&');

const ht = [
  '# Generated by scripts/postbuild.mjs – do not edit by hand.',
  'Options -Indexes',
  'ErrorDocument 404 /404.html',
  'RewriteEngine On',
  '# Force HTTPS and www',
  'RewriteCond %{HTTPS} off [OR]',
  'RewriteCond %{HTTP_HOST} !^www\\. [NC]',
  'RewriteRule ^ https://www.cspconsulting.ma%{REQUEST_URI} [L,R=301]',
  '# Old product listing URLs (produits.php?categoryId=…)',
];
for (const [cat, to] of Object.entries(r.productQuery)) {
  if (cat === '*') continue;
  const enc = encodeURIComponent(cat).replace(/%20/g, '(%20|\\+| )').replace(/`/g, '%60');
  ht.push(`RewriteCond %{QUERY_STRING} (^|&)categoryId=${enc.replace(/%60/g, '(%60|`)')}(&|$) [NC]`, `RewriteRule ^produits\\.php$ ${to}? [L,R=301]`);
}
ht.push(`RewriteRule ^produits\\.php$ ${r.productQuery['*']}? [L,R=301]`);
for (const [from, to] of Object.entries(r.paths)) ht.push(`RewriteRule ^${esc(from.slice(1))}$ ${to} [L,R=301]`);
for (const [from, to] of Object.entries(r.prefixes)) ht.push(`RewriteRule ^${esc(from.slice(1))} ${to} [L,R=301]`);
ht.push(
  '',
  '<IfModule mod_headers.c>',
  '  Header always set Strict-Transport-Security "max-age=31536000"',
  '  Header always set X-Content-Type-Options "nosniff"',
  '  Header always set X-Frame-Options "SAMEORIGIN"',
  '  Header always set Referrer-Policy "strict-origin-when-cross-origin"',
  '  <FilesMatch "\\.(webp|jpg|png|svg|woff2|css|js)$">',
  '    Header set Cache-Control "public, max-age=31536000, immutable"',
  '  </FilesMatch>',
  '</IfModule>',
);
writeFileSync('dist/.htaccess', ht.join('\n') + '\n');

const nl = [];
for (const [from, to] of Object.entries(r.paths)) nl.push(`${base}${from} ${base}${to} 301`);
for (const [from, to] of Object.entries(r.prefixes)) nl.push(`${base}${from}* ${base}${to} 301`);
nl.push(`${base}/produits.php ${base}${r.productQuery['*']} 301`);
writeFileSync('dist/_redirects', nl.join('\n') + '\n');

// sitemap.xml + robots.txt
const pages = [];
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f === 'index.html') pages.push(p.slice('dist'.length).replace(/index\.html$/, ''));
  }
})('dist');
const urls = pages.filter((p) => !p.startsWith('/404')).sort();
writeFileSync(
  'dist/sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
    .map((u) => `  <url><loc>${site}${base}${u}</loc></url>`)
    .join('\n')}\n</urlset>\n`,
);
writeFileSync('dist/robots.txt', isProd ? `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n` : 'User-agent: *\nDisallow: /\n');
console.log(`postbuild: ${Object.keys(r.paths).length} redirects, ${urls.length} URLs in sitemap`);
